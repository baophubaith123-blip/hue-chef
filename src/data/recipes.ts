function steps(
  recipeId: string,
  items: Array<{ title: string; description: string; durationSeconds: number }>,
) {
  return items.map((item, index) => ({
    id: `${recipeId}-step-${index + 1}`,
    order: index + 1,
    ...item,
  }));
}

